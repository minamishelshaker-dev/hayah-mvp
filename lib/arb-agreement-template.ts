// A starting text for the arbitration agreement drafted on the platform. GUIDANCE ONLY: it must be reviewed by a lawyer
// before real use, like the settlement template. Every [..] must be replaced; the database refuses to open the text for
// signature while a bracket remains.
export function arbAgreementTemplate(i: { arbNumber: string; claimant: string; respondent: string; valueEgp: number }): string {
  return `اتفاق تحكيم

رقم الملف على المنصة: ${i.arbNumber}

أولًا: الطرفان
الطرف الأول (مقدّم الطلب): ${i.claimant}
الطرف الثاني: ${i.respondent}

ثانيًا: موضوع الاتفاق
اتفق الطرفان على إحالة النزاع الآتي بينهما إلى التحكيم وفقًا لأحكام القانون رقم 27 لسنة 1994 في شأن التحكيم في المواد المدنية والتجارية: [وصف النزاع وسنده التعاقدي، مثل رقم العقد وتاريخه].
القيمة التقديرية للنزاع: ${Number(i.valueEgp).toLocaleString('en-US')} جنيه مصري.

ثالثًا: المحكّم
يُحال النزاع إلى محكّم منفرد يتفق عليه الطرفان من دليل المحكّمين المعتمدين على منصة حياة. ولا يجوز أن يكون محكّمًا من عمل وسيطًا بين الطرفين في هذا النزاع.

رابعًا: مكان التحكيم ولغته والقانون الواجب التطبيق
مكان التحكيم: [المدينة].
لغة الإجراءات: [اللغة العربية].
القانون الواجب التطبيق على موضوع النزاع: [القانون المصري].

خامسًا: الإجراءات
تجري الإجراءات وفق قواعد استخدام المنصة في التحكيم التي قبلها الطرفان، وبما لا يخالف القواعد الآمرة في القانون. يحدد المحكّم الجدول الإجرائي وتبادل المذكرات وجلسات الاستماع.

سادسًا: السرية
يلتزم الطرفان والمحكّم بسرية إجراءات التحكيم ومستنداته وحكمه، إلا ما يلزم الإفصاح عنه لتنفيذ الحكم أو الطعن عليه أو بحكم القانون.

سابعًا: الأتعاب والنفقات
يتحمل الطرفان أتعاب المحكّم ونفقات التحكيم على النحو الآتي: [النسبة أو الاتفاق].

ثامنًا: حكم التحكيم
يصدر الحكم مكتوبًا ومسببًا وموقعًا من المحكّم، ويكون ملزمًا للطرفين وفق أحكام القانون.

تاسعًا: التوقيع الإلكتروني
يقرّ كل من الطرفين بأنه قرأ هذا الاتفاق وفهمه، وأنه يوقّعه إلكترونيًا عبر منصة حياة بتأكيد كلمة مروره، وأن هذا التوقيع صادر عنه.`
}
